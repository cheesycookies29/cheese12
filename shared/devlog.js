// Compare 'x.y.z' or 'x.y.z-stage' versions by their numbers.
export function compareVersions(a, b) {
  const nums = (v) => v.split('-')[0].split('.').map(Number);
  const [x, y] = [nums(a), nums(b)];
  return x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
}
